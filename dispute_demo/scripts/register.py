"""Register the triage rules, task definitions, user forms and both workflows.

    python scripts/register.py

Orkes: triage is a BUSINESS_RULE task that references a decision rule saved in Orkes by name
(Orkes 5.6+: Definitions > Decision Rules). rules/dispute_rules.csv is that rule's starting
content: every run of this script saves it, so a demo always starts from the repo's rules.
Edit the rule live in the Orkes UI; the next case uses it, with no deploy and no cache delay.

Conductor OSS (CONDUCTOR_FLAVOR=oss): there are no decision rules or user forms. Triage becomes an
INLINE (JavaScript) task generated from the same CSV, with the same output, so the rest of the
workflow is unchanged. To change the rules on OSS, edit the CSV and run this script again.
"""

from __future__ import annotations

import csv
import io
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.orkes import OrkesError, client  # noqa: E402

RULE_NAME = "dispute_triage_rules"
RULE_INPUTS = {
    "outsideWindow": "${enrich_case.output.outsideWindow}",
    "amount": "${enrich_case.output.amount}",
    "category": "${enrich_case.output.category}",
    "priorDisputes90d": "${enrich_case.output.priorDisputes90d}",
}


def save_rule(o) -> None:
    csv = (ROOT / "rules" / "dispute_rules.csv").read_text()
    try:
        o.call("POST", "/business-rules", json={"name": RULE_NAME, "csvData": csv})
    except OrkesError as e:
        if e.status == 403:
            sys.exit(f"Orkes refused to save decision rule '{RULE_NAME}' (403). Give the application behind "
                     "CONDUCTOR_AUTH_KEY the 'Business Rule Manager' (or Metadata Manager) role in "
                     "Access Control > Applications, then run this again.")
        raise
    print(f"Saved decision rule {RULE_NAME} from rules/dispute_rules.csv")


def triage_task() -> dict:
    return {
        "name": "triage_rules",
        "taskReferenceName": "triage_rules",
        "type": "BUSINESS_RULE",
        "description": f"Dispute triage: decision rule '{RULE_NAME}' (Definitions > Decision Rules). First matching row wins.",
        "inputParameters": {
            "ruleName": RULE_NAME,
            "executionStrategy": "FIRE_FIRST",
            "inputColumns": RULE_INPUTS,
            "outputColumns": ["route", "reason"],
        },
    }


def _condition(cell: str) -> dict | None:
    """One CSV cell -> a condition the INLINE script understands (None = matches anything)."""
    cell = cell.strip()
    if cell in ("", "Any"):
        return None
    m = re.fullmatch(r"(>=|<=|>|<)\s*(-?[\d.]+)", cell)
    if m:
        return {"op": m.group(1), "value": float(m.group(2))}
    m = re.fullmatch(r"inList\(\{(.*)\}\)", cell)
    if m:
        return {"op": "in", "values": [v.strip().strip('"') for v in m.group(1).split(",")]}
    return {"op": "=", "value": cell}


def oss_triage_task() -> dict:
    """The decision table as an INLINE task: rows from the CSV, first matching row wins."""
    rows = list(csv.DictReader(io.StringIO((ROOT / "rules" / "dispute_rules.csv").read_text())))
    rules = [{"when": {k: c for k in RULE_INPUTS if (c := _condition(r[k])) is not None},
              "route": r["route"], "reason": r["reason"]} for r in rows]
    script = "\n".join([
        "(function () {",
        "  // Generated from rules/dispute_rules.csv by scripts/register.py. First matching row wins.",
        "  var rules = [",
        ",\n".join("    " + json.dumps(r) for r in rules),
        "  ];",
        "  function ok(v, c) {",
        "    if (c.op === '=') return String(v).toLowerCase() === String(c.value).toLowerCase();",
        "    if (c.op === 'in') return c.values.indexOf(String(v)) >= 0;",
        "    var n = Number(v);",
        "    return c.op === '>' ? n > c.value : c.op === '>=' ? n >= c.value :",
        "           c.op === '<' ? n < c.value : n <= c.value;",
        "  }",
        "  for (var i = 0; i < rules.length; i++) {",
        "    var hit = true;",
        "    for (var k in rules[i].when) { if (!ok($[k], rules[i].when[k])) { hit = false; break; } }",
        "    if (hit) return {route: rules[i].route, reason: rules[i].reason};",
        "  }",
        "  return {route: 'HUMAN_REVIEW', reason: 'No rule matched'};",
        "})();",
    ])
    return {
        "name": "triage_rules",
        "taskReferenceName": "triage_rules",
        "type": "INLINE",
        "description": "Dispute triage: rules from rules/dispute_rules.csv (generated by scripts/register.py). First matching row wins.",
        "inputParameters": {"evaluatorType": "graaljs", "expression": script, **RULE_INPUTS},
    }


def load(rel: str):
    return json.loads((ROOT / rel).read_text())


def main() -> None:
    o = client()
    if not o.is_oss:
        save_rule(o)

    task_defs = load("workflows/task_defs.json")
    try:
        o.register_task_defs(task_defs)
        print(f"Created {len(task_defs)} task definitions")
    except OrkesError:
        o.update_task_defs(task_defs)
        print(f"Updated {len(task_defs)} task definitions")

    if not o.is_oss:  # OSS has no user forms; its HUMAN tasks are completed through the console
        for form_file in sorted((ROOT / "forms").glob("*.json")):
            form = json.loads(form_file.read_text())
            o.save_user_form(form)
            print(f"Saved user form {form['name']} v{form['version']}")

    case_wf = load("workflows/dispute_case.json")
    triage = oss_triage_task() if o.is_oss else triage_task()
    case_wf["tasks"] = [triage if t == "__TRIAGE_TASK__" else t for t in case_wf["tasks"]]
    intake_wf = load("workflows/dispute_intake.json")
    o.upsert_workflow_defs([case_wf, intake_wf])
    how = "INLINE task from rules/dispute_rules.csv" if o.is_oss else f"decision rule {RULE_NAME}"
    print(f"Registered workflows dispute_case (triage: {how}) and dispute_intake")
    print(f"{'Conductor' if o.is_oss else 'Orkes'} UI: {o.ui_base}/workflowDef/dispute_intake")


if __name__ == "__main__":
    main()
